import test from 'node:test';
import assert from 'node:assert/strict';
import { registerComposerAttachmentInvalidator, setComposerAttachmentLifecycleEnabled } from './composerAttachmentLifecycle';
test('plugin-wide disable invalidates lazy managers; late registration is also fenced', () => {
  let calls=0;
  setComposerAttachmentLifecycleEnabled(false);
  registerComposerAttachmentInvalidator(()=>calls++);
  assert.equal(calls,1);
  setComposerAttachmentLifecycleEnabled(true);
  assert.equal(calls,1);
  setComposerAttachmentLifecycleEnabled(false);
  assert.equal(calls,2);
  let lateCalls=0;
  registerComposerAttachmentInvalidator(()=>lateCalls++);
  assert.equal(lateCalls,1);
  setComposerAttachmentLifecycleEnabled(true);
  assert.equal(lateCalls,1);
  setComposerAttachmentLifecycleEnabled(false);
  assert.equal(lateCalls,2);
});
