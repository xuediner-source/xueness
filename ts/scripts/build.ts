/** Compile a relocatable JS workspace with production dependencies and manifests. */
import { cpSync, existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, realpathSync, rmSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import ts from "typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = join(root, "dist");
const marker = join(output, ".xueness-generated-build");
if (existsSync(output)) {
  if (!existsSync(marker) || realpathSync(output) !== output || relative(root, output) !== "dist") throw new Error("refusing to replace an unrecognized build directory");
  rmSync(output, { recursive: true });
}
mkdirSync(output, { recursive: true });
writeFileSync(marker, "Generated by ts/scripts/build.ts\n");
let count = 0;
function tree(source: string, destination: string): void {
  mkdirSync(destination, { recursive: true });
  for (const entry of readdirSync(source, { withFileTypes: true })) {
    if (["test", "tests", "node_modules", "dist"].includes(entry.name)) continue;
    const from = join(source, entry.name), to = join(destination, entry.name);
    // Account seeds are local user credentials, never distributable assets.
    if (relative(root, from).replaceAll("\\", "/") === "plugins/workbuddy/assets/auths") continue;
    if (entry.isDirectory()) { tree(from, to); continue; }
    if (entry.name.endsWith(".ts") && !entry.name.endsWith(".d.ts")) {
      const result = ts.transpileModule(readFileSync(from, "utf8"), { fileName: from, compilerOptions: {
        target: ts.ScriptTarget.ES2024, module: ts.ModuleKind.ESNext,
        rewriteRelativeImportExtensions: true, sourceMap: true, inlineSources: true,
      } });
      const target = to.slice(0, -3) + ".js";
      writeFileSync(target, result.outputText);
      if (result.sourceMapText) writeFileSync(target + ".map", result.sourceMapText);
      count++;
    } else if (entry.name === "package.json") {
      const pkg = JSON.parse(readFileSync(from, "utf8"));
      // Exports and bin paths must point at executable JavaScript after relocation.
      for (const field of ["exports", "bin", "main"]) if (pkg[field]) pkg[field] = JSON.parse(JSON.stringify(pkg[field]).replace(/\.ts"/g, '.js"'));
      delete pkg.devDependencies;
      writeFileSync(to, JSON.stringify(pkg, null, 2) + "\n");
    } else if (!entry.name.endsWith(".ts")) cpSync(from, to);
  }
}
for (const group of ["packages", "plugins", "apps"]) tree(join(root, group), join(output, group));
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
delete pkg.devDependencies;
pkg.scripts = { serve: "node apps/server/src/main.js" };
writeFileSync(join(output, "package.json"), JSON.stringify(pkg, null, 2) + "\n");
// The bundled manifests are catalog data (route families, defaults, dependencies).
cpSync(join(root, "catalog"), join(output, "catalog"), { recursive: true });
for (const name of ["LICENSE", "NOTICE.md"]) cpSync(join(root, "..", name), join(output, name));
// Ship the tested standalone runtime, independent of PATH and Electron's ABI.
const runtime = join(output, "runtime");
mkdirSync(runtime);
cpSync(process.execPath, join(runtime, process.platform === "win32" ? "node.exe" : "node"));
// Windows archives keep LICENSE next to node.exe; POSIX archives keep it beside bin/.
const nodeLicense = [dirname(process.execPath), dirname(dirname(process.execPath))].map((dir) => join(dir, "LICENSE")).find((path) => existsSync(path));
if (!nodeLicense) throw new Error("Node redistribution requires the runtime LICENSE next to node or beside its bin directory");
cpSync(nodeLicense, join(runtime, "LICENSE.node"));
const npm = process.env.npm_execpath;
if (!npm) throw new Error("run the build with npm run build");
execFileSync(process.execPath, [npm, "install", "--omit=dev", "--ignore-scripts", "--no-audit", "--no-fund"], { cwd: output, stdio: "inherit", windowsHide: true });
// npm workspaces on Windows are absolute junctions. Materialize them so a
// copied installer/runtime has no reference to this development checkout.
const scope = join(output, "node_modules", "@xueness");
for (const name of readdirSync(scope)) {
  const link = join(scope, name);
  if (!lstatSync(link).isSymbolicLink()) throw new Error(`expected generated workspace link: ${name}`);
  const source = realpathSync(link), rel = relative(output, source);
  if (rel.startsWith("..") || !["packages", "plugins", "apps"].some((group) => rel.startsWith(group + "/") || rel.startsWith(group + "\\"))) throw new Error("workspace link escapes the build");
  unlinkSync(link); cpSync(source, link, { recursive: true, dereference: true });
}
process.stdout.write(`Built ${count} JavaScript modules in ${output}\n`);
