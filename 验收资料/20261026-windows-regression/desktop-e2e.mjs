import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { startDesktopFixture } from './desktop-fixture.mjs';

const evidence = new URL('./desktop-e2e/', import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1');
mkdirSync(evidence, { recursive: true });
const fixture = await startDesktopFixture(process.argv[2] ?? new URL('../../desktop/release/win-unpacked/Xueness.exe', import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1'), join(evidence, `data-${Date.now()}`));
const { page, api } = fixture;
const checks = [];
const record = (name, details = {}) => { checks.push({ name, ...details }); console.log(JSON.stringify({ passed: name, ...details })); };
const waitSession = async (id, predicate) => {
  for(let i=0;i<150;i++) { const result=await api(`/api/sessions/${id}`); if(predicate(result.body)) return result.body; await page.waitForTimeout(100); }
  throw new Error(`Session did not settle: ${id}`);
};
try {
  const skip = page.getByTestId('desktop-permission-onboarding-skip-all');
  await skip.waitFor({timeout:15000});
  await skip.click();
  await page.getByTestId('desktop-permission-onboarding').waitFor({state:'hidden'});
  const saved = await api('/api/providers', { id: 'local-e2e', name: '本地全链路验收', baseUrl: fixture.modelBase, model: 'local-e2e', apiKey: 'isolated-fixture', allowLoopbackHttp: true });
  assert.equal(saved.status, 200, JSON.stringify(saved.body));
  assert.equal((await api('/api/providers/default', { providerId: 'local-e2e', model: 'local-e2e' })).status, 200);
  await page.reload();
  await page.locator('textarea.xn-composer__input').waitFor({ timeout: 20000 });
  record('packaged-desktop-startup');
  await page.screenshot({ path:join(evidence, 'startup.png') });
  const editor = page.locator('textarea.xn-composer__input').first();
  await editor.fill('E2E_READ 请读取 sample.txt 并报告其中内容。');
  const firstRun = page.waitForResponse(r => /\/api\/sessions\/[0-9a-f]+\/commands$/.test(new URL(r.url()).pathname) && r.request().method()==='POST', { timeout:30000 });
  firstRun.catch(()=>{});
  await page.getByRole('button', { name:'发送', exact:true }).click();
  const firstResponse = await firstRun;
  assert.equal(firstResponse.status(), 200);
  const sid = new URL(firstResponse.url()).pathname.split('/')[3];
  const first = await waitSession(sid, s=>s.status==='completed');
  const firstJournal=JSON.parse(readFileSync(join(fixture.data,'state',`${sid}.json`),'utf8'));
  assert.equal(firstJournal.results[Object.keys(firstJournal.results).find(k => k.startsWith('e2e-read'))]?.ok, true, JSON.stringify(firstJournal.results));
  await page.getByText('已读取 sample.txt：', {exact:false}).first().waitFor({timeout:15000});
  record('UI-send-stream-file-tool-journal', { sessionId:sid, modelRequests:fixture.modelRequests.length, verified:first.completion?.verified });
  await page.screenshot({ path:join(evidence,'read-completed.png') });
  await page.getByTestId('composer-attachment-input').setInputFiles(join(fixture.workspace,'sample.txt'));
  await page.getByTestId('composer-attachment-preview').click();
  await page.getByTestId('composer-attachment-preview-text').waitFor();
  assert.match(await page.getByTestId('composer-attachment-preview-text').innerText(), /full-chain fixture/);
  await page.getByRole('button',{name:'关闭预览',exact:true}).click();
  await page.getByRole('button',{name:'移除附件：sample.txt',exact:true}).click();
  record('UI-attachment-commit-preview-remove');
  await editor.fill('E2E_WRITE 请创建 output/e2e.txt，等待我确认后写入。');
  const secondRun = page.waitForResponse(r => new URL(r.url()).pathname===`/api/sessions/${sid}/commands` && r.request().method()==='POST', {timeout:30000});
  secondRun.catch(()=>{});
  await page.getByRole('button',{name:'发送',exact:true}).click();
  assert.equal((await secondRun).status(),200);
  await page.getByRole('button',{name:'允许',exact:true}).waitFor({timeout:15000});
  await page.screenshot({path:join(evidence,'write-approval.png')});
  await page.getByRole('button',{name:'允许',exact:true}).click();
  const second=await waitSession(sid,s=>s.status==='completed');
  const secondJournal=JSON.parse(readFileSync(join(fixture.data,'state',`${sid}.json`),'utf8'));
  assert.equal(secondJournal.results[Object.keys(secondJournal.results).find(k=>k.startsWith('e2e-write'))].ok,true);
  assert.equal(readFileSync(join(fixture.workspace,'output','e2e.txt'),'utf8'),'E2E write approved 20261026\n');
  assert.equal(second.completion?.verified,true,JSON.stringify(second.completion));
  record('UI-write-approval-resume', {verified:second.completion?.verified});
  await page.getByRole('button',{name:'打开设置',exact:true}).click();
  await page.getByTestId('xn-settings-nav-plugins').click();
  await page.getByTestId('xn-installed-plugin-deepseek_harness').waitFor();
  record('UI-complete-plugin-catalog',{cards:await page.locator('[data-testid^="xn-installed-plugin-"]').count()});
  const native = page.getByTestId('xn-installed-plugin-native_ops').locator('input[type=checkbox]');
  const disabled=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/plugins/native_ops'&&r.request().method()==='POST');
  await native.click();
  await disabled;
  assert.equal((await api('/api/plugins')).body.plugins.find(p=>p.id==='native_ops').effective,false);
  const enabled=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/plugins/native_ops'&&r.request().method()==='POST');
  await native.click();
  await enabled;
  assert.equal((await api('/api/plugins')).body.plugins.find(p=>p.id==='native_ops').effective,true);
  record('UI-plugin-switch-backend-effective');
  const extensions=page.locator('.xn-settings-view__extensions > summary');
  if(await extensions.isVisible()) await extensions.click();
  const navs=await page.locator('[data-testid^="xn-settings-nav-"]').evaluateAll(es=>es.map(e=>e.dataset.testid));
  const panels=[];
  for(const id of navs) {
    const nav=page.getByTestId(id);
    if(!await nav.isVisible()) { if(await extensions.isVisible()) await extensions.click(); }
    await nav.click();
    await page.waitForFunction(()=>{const body=document.querySelector('[data-testid="xn-settings-section-content"]');return body&&body.textContent.trim().length>0&&!body.textContent.includes('正在加载界面')&&!body.textContent.includes('正在加载设置');},{},{timeout:20000});
    assert.equal(await nav.getAttribute('aria-current'),'page');
    const text=await page.locator('#xn-settings-view-content').innerText();
    assert.ok(text.trim().length>10,id);
    panels.push({id,characters:text.length});
  }
  record('UI-settings-all-panels',{panels});
  await page.getByTestId('xn-settings-search').fill('外观');
  assert.equal(await page.getByTestId('xn-settings-nav-appearance').isVisible(),true);
  assert.equal(await page.getByTestId('xn-settings-nav-general').count(),0);
  await page.getByTestId('xn-settings-search').fill('');
  await page.getByTestId('xn-settings-nav-appearance').click();
  await page.getByRole('combobox',{name:'界面主题',exact:true}).click();
  await page.getByRole('option',{name:'深色',exact:true}).click();
  await page.waitForFunction(()=>document.documentElement.dataset.xnTheme==='dark');
  assert.equal((await api('/api/settings/appearance')).body.values.theme,'dark');
  await page.screenshot({path:join(evidence,'dark-theme.png')});
  record('UI-theme-saved-to-backend');
  await page.getByTestId('xn-settings-nav-general').click();
  const cancellation=page.getByRole('switch',{name:'立即停止模型与工具请求',exact:true});
  await cancellation.waitFor();
  const cancellationSaved=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/settings/general'&&r.request().method()==='POST');
  await cancellation.click();
  await cancellationSaved;
  assert.equal((await api('/api/settings/general')).body.values.sessionsCancelPropagateEnabled,true);
  record('UI-cancellation-setting-wired');
  await page.getByTestId('xn-settings-back').click();
  await editor.fill('E2E_HOLD 等待我补充，然后测试停止。');
  await page.getByRole('button',{name:'发送',exact:true}).click();
  await page.getByText('正在等待取消操作。',{exact:false}).first().waitFor({timeout:15000});
  await editor.fill('E2E_QUEUE 这是运行中的排队消息。');
  await editor.press('Control+Enter');
  let queue;
  for(let n=0;n<80;n++) { queue=(await api(`/api/sessions/${sid}/queue`)).body; if(queue.queued_messages?.some(q=>q.text.includes('E2E_QUEUE'))) break; await page.waitForTimeout(100); }
  assert.ok(queue.queued_messages?.some(q=>q.text.includes('E2E_QUEUE')),JSON.stringify(queue));
  record('UI-running-queue-admission');
  const stopResponse=page.waitForResponse(r=>r.request().method()==='POST'&&new URL(r.url()).pathname===`/api/sessions/${sid}/commands`&&r.request().postDataJSON()?.type==='stop');
  stopResponse.catch(()=>{});
  await page.getByRole('button',{name:'停止',exact:true}).click();
  console.log(JSON.stringify({stopAck:await (await stopResponse).json()}));
  const stopped=await waitSession(sid,s=>!['running','pending','cancelling'].includes(s.status));
  record('UI-stop-preserves-partial-output',{status:stopped.status});
  await page.screenshot({path:join(evidence,'stopped.png')});
  await fixture.app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(800,650));
  await page.screenshot({path:join(evidence,'narrow-window.png')});
  const layout=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth}));
  assert.ok(layout.scrollWidth<=layout.width+1,JSON.stringify(layout));
  record('UI-narrow-window-no-horizontal-overflow',layout);
  await fixture.app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1280,840));
  await fixture.close();
  const restarted=await startDesktopFixture(process.argv[2] ?? new URL('../../desktop/release/win-unpacked/Xueness.exe',import.meta.url).pathname.replace(/^\/([A-Z]:)/,'$1'),fixture.data);
  try {
    const restored=(await restarted.api(`/api/sessions/${sid}`)).body;
    assert.equal(restored.id,sid);
    assert.equal(readFileSync(join(fixture.workspace,'output','e2e.txt'),'utf8'),'E2E write approved 20261026\n');
    await restarted.page.getByText('E2E_READ 请读取 sample.txt 并报告其中内容。',{exact:false}).first().waitFor();
    await restarted.page.screenshot({path:join(evidence,'full-restart.png')});
    record('full-desktop-restart-session-and-file-preserved',{sessionId:sid});
  } finally {await restarted.close();}
} catch (error) {
  await page.screenshot({ path:join(evidence, 'failure.png') }).catch(() => {});
  writeFileSync(join(evidence, 'failure-ui.txt'), await page.locator('body').innerText().catch(() => 'unavailable'));
  console.error(error);
  process.exitCode = 1;
} finally {
  writeFileSync(join(evidence, 'result.json'), JSON.stringify({ checks, modelRequests:fixture.modelRequests, responses:fixture.responses, pageErrors:fixture.errors }, null, 2));
  await fixture.close();
}
